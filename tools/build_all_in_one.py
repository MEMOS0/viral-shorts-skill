"""Concatenate SKILL.md, references, templates and examples into ALL_IN_ONE.md (for chat models that
can't read a repo). usage: python tools/build_all_in_one.py [--check]  (--check exits 1 if stale)"""
import glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ORDER = ["SKILL.md", "AGENTS.md"] + sorted(glob.glob("references/*.md", root_dir=ROOT)) + sorted(glob.glob("templates/*", root_dir=ROOT)) \
        + sorted(glob.glob("examples/*.md", root_dir=ROOT)) + ["data/analysis_summary.md"]

def build():
    parts = ["# viral-shorts-skill v3: all files in one\n\nGenerated by tools/build_all_in_one.py; do not edit by hand.\n"]
    for f in ORDER:
        p = os.path.join(ROOT, f)
        if os.path.exists(p):
            parts.append(f"\n<!-- ===== {f.replace(os.sep, '/')} ===== -->\n\n" + open(p, encoding="utf-8").read().rstrip() + "\n")
    return "".join(parts)

if __name__ == "__main__":
    out = os.path.join(ROOT, "ALL_IN_ONE.md"); new = build()
    if "--check" in sys.argv:
        old = open(out, encoding="utf-8").read() if os.path.exists(out) else ""
        sys.exit(0 if old == new else "ALL_IN_ONE.md is stale: run python tools/build_all_in_one.py")
    open(out, "w", encoding="utf-8", newline="\n").write(new); print("wrote", out, len(new), "chars")
